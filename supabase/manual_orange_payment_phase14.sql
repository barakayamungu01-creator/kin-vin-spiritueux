-- ------------------------------------------------------------
-- Déclaration du paiement d'acompte.
-- ------------------------------------------------------------
create table if not exists public.payment_deposits (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  sender_network text not null
    check(sender_network in ('orange_money','mpesa','airtel_money')),
  sender_phone text not null,
  transaction_reference text not null,
  amount_expected numeric(12,2) not null,
  amount_declared numeric(12,2) not null,
  proof_path text,
  status text not null default 'pending_verification'
    check(status in ('pending_verification','deposit_paid','rejected')),
  rejection_reason text,
  verified_by uuid references auth.users(id) on delete set null,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists payment_deposits_order_idx on public.payment_deposits(order_id);
create index if not exists payment_deposits_status_idx on public.payment_deposits(status);
create unique index if not exists payment_deposits_network_ref_unique
on public.payment_deposits(sender_network,transaction_reference);

alter table public.payment_deposits enable row level security;

