create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  v_account_type text := coalesce(new.raw_user_meta_data->>'account_type','');
  v_role text := case when v_account_type='professional' then 'professional' else 'customer' end;
  v_status text := case when v_account_type='professional' then 'pending' else 'active' end;
begin
  insert into public.profiles (id,email,role,status)
  values (new.id,new.email,v_role,v_status)
  on conflict (id) do update
  set email=excluded.email,
      role=case when public.profiles.role in ('admin','super_admin') then public.profiles.role else excluded.role end,
      status=case when public.profiles.role in ('admin','super_admin') then public.profiles.status else excluded.status end,
      updated_at=now();
  return new;
end;
$$;

