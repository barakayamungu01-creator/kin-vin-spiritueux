create or replace function public.is_kin_admin()
returns boolean
language sql
security definer set search_path=public
stable
as $$
  select exists(
    select 1 from public.profiles p
    where p.id=auth.uid() and p.role in ('admin','super_admin') and p.status='active'
  );
$$;
grant execute on function public.is_kin_admin() to authenticated;

