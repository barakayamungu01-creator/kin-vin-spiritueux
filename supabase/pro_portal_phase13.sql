create or replace function public.handle_new_pro_account()
returns trigger
language plpgsql
security definer set search_path=public
as $$
begin
  if coalesce(new.raw_user_meta_data->>'account_type','')='professional' then
    insert into public.pro_accounts (
      user_id,email,company,trade_name,activity,monthly_volume,commune,address,
      first_name,last_name,phone,business_id,plan,requested_plan,account_status
    )
    values (
      new.id,new.email,
      coalesce(new.raw_user_meta_data->>'company','Entreprise'),
      nullif(new.raw_user_meta_data->>'tradeName',''),
      nullif(new.raw_user_meta_data->>'activity',''),
      nullif(new.raw_user_meta_data->>'volume',''),
      nullif(new.raw_user_meta_data->>'commune',''),
      nullif(new.raw_user_meta_data->>'address',''),
      nullif(new.raw_user_meta_data->>'firstName',''),
      nullif(new.raw_user_meta_data->>'lastName',''),
      nullif(new.raw_user_meta_data->>'phone',''),
      nullif(new.raw_user_meta_data->>'businessId',''),
      'essential','essential','pending'
    )
    on conflict (user_id) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists zz_auth_create_pro_account on auth.users;
create trigger zz_auth_create_pro_account
after insert on auth.users
for each row execute procedure public.handle_new_pro_account();

insert into public.pro_accounts (user_id,email,company,plan,account_status)
select u.id,u.email,coalesce(u.raw_user_meta_data->>'company','Entreprise'),'essential',
       case when p.status='active' then 'active' else 'pending' end
from auth.users u
join public.profiles p on p.id=u.id
where p.role='professional'
on conflict (user_id) do nothing;

create table if not exists public.pro_price_rules (
  id bigint generated by default as identity primary key,
  plan text not null check (plan in ('essential','business','premium')),
  product_id bigint references public.products(id) on delete cascade,
  category text,
  min_qty integer not null default 1 check (min_qty > 0),
  discount_percent numeric(5,2) not null check (discount_percent between 0 and 30),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

insert into public.pro_price_rules(plan,product_id,category,min_qty,discount_percent)
select * from (values
 ('essential',null::bigint,null::text,1,5.00),
 ('essential',null::bigint,null::text,6,6.00),
 ('essential',null::bigint,null::text,12,8.00),
 ('business',null::bigint,null::text,1,8.00),
 ('business',null::bigint,null::text,6,10.00),
 ('business',null::bigint,null::text,12,12.00),
 ('premium',null::bigint,null::text,1,12.00),
 ('premium',null::bigint,null::text,6,14.00),
 ('premium',null::bigint,null::text,12,16.00)
) v(plan,product_id,category,min_qty,discount_percent)
where not exists (
  select 1 from public.pro_price_rules r
  where r.plan=v.plan and r.product_id is null and r.category is null and r.min_qty=v.min_qty
);

