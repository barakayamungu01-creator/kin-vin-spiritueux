-- ------------------------------------------------------------
-- Création sécurisée d'une commande publique.
-- Le serveur recalcule tous les prix depuis public.products.
-- ------------------------------------------------------------
create or replace function public.create_manual_mobile_order(
  p_customer jsonb,
  p_items jsonb,
  p_delivery jsonb,
  p_network text,
  p_sender_phone text,
  p_transaction_reference text,
  p_amount_declared numeric,
  p_proof_path text default null
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  item jsonb;
  prod public.products%rowtype;
  qty integer;
  unit_price numeric;
  v_subtotal numeric := 0;
  v_delivery_fee numeric := 0;
  v_total numeric := 0;
  v_deposit_percent numeric := 50;
  v_deposit numeric := 0;
  v_balance numeric := 0;
  v_order_id uuid;
  v_order_no text;
  v_payment_id uuid;
  v_commune text;
  v_customer_name text;
  v_customer_phone text;
  v_address text;
begin
  if p_network not in ('orange_money','mpesa','airtel_money') then
    raise exception 'Réseau de paiement invalide';
  end if;

  if coalesce(trim(p_transaction_reference),'')='' then
    raise exception 'Référence transaction obligatoire';
  end if;

  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items)=0 then
    raise exception 'Commande vide';
  end if;

  v_customer_name := trim(coalesce(p_customer->>'name',''));
  v_customer_phone := trim(coalesce(p_customer->>'phone',''));
  v_address := trim(coalesce(p_customer->>'address',''));
  v_commune := trim(coalesce(p_delivery->>'commune',''));

  if v_customer_name='' or v_customer_phone='' or v_address='' or v_commune='' then
    raise exception 'Informations de livraison incomplètes';
  end if;

  select coalesce(deposit_percent,50)
  into v_deposit_percent
  from public.payment_settings
  where active=true
  order by id
  limit 1;

  v_deposit_percent := coalesce(v_deposit_percent,50);

  for item in select * from jsonb_array_elements(p_items)
  loop
    qty := greatest(1,coalesce((item->>'quantity')::integer,1));

    select * into prod
    from public.products
    where id=(item->>'productId')::bigint
      and active=true;

    if not found then
      raise exception 'Produit introuvable';
    end if;

    unit_price := coalesce(nullif(prod.promo_price,0),prod.price);
    v_subtotal := v_subtotal + unit_price*qty;
  end loop;

  v_delivery_fee := case lower(v_commune)
    when 'gombe' then 4
    when 'lingwala' then 5
    when 'kintambo' then 6
    when 'ngaliema' then 7
    when 'limete' then 6
    when 'lemba' then 7
    when 'mont-ngafula' then 10
    when 'mont ngafula' then 10
    else 0
  end;

  v_total := round(v_subtotal + v_delivery_fee,2);
  v_deposit := round(v_total * v_deposit_percent / 100,2);
  v_balance := round(v_total - v_deposit,2);

  if abs(coalesce(p_amount_declared,0)-v_deposit) > 0.01 then
    raise exception 'Le montant déclaré ne correspond pas à l''acompte attendu';
  end if;

  v_order_no :=
    'KIN-' || to_char(current_date,'YYYYMMDD') || '-' ||
    upper(substr(replace(gen_random_uuid()::text,'-',''),1,6));

  insert into public.orders(
    order_number,
    customer_name,
    customer_phone,
    delivery_address,
    delivery_commune,
    subtotal,
    delivery_fee,
    total,
    currency,
    payment_method,
    payment_status,
    order_status,
    deposit_percent,
    deposit_amount,
    balance_amount,
    balance_status,
    metadata
  )
  values(
    v_order_no,
    v_customer_name,
    v_customer_phone,
    v_address,
    v_commune,
    v_subtotal,
    v_delivery_fee,
    v_total,
    'USD',
    'manual_mobile_money',
    'deposit_verification',
    'awaiting_deposit_verification',
    v_deposit_percent,
    v_deposit,
    v_balance,
    'due_on_delivery',
    jsonb_build_object(
      'source','web_checkout',
      'delivery_type',coalesce(p_delivery->>'deliveryType','Standard')
    )
  )
  returning id into v_order_id;

  for item in select * from jsonb_array_elements(p_items)
  loop
    qty := greatest(1,coalesce((item->>'quantity')::integer,1));

    select * into prod
    from public.products
    where id=(item->>'productId')::bigint
      and active=true;

    unit_price := coalesce(nullif(prod.promo_price,0),prod.price);

    insert into public.order_items(
      order_id,product_id,sku,product_name,quantity,unit_price,line_total
    )
    values(
      v_order_id,
      prod.id,
      prod.sku,
      prod.name,
      qty,
      unit_price,
      round(unit_price*qty,2)
    );
  end loop;

  insert into public.payment_deposits(
    order_id,
    sender_network,
    sender_phone,
    transaction_reference,
    amount_expected,
    amount_declared,
    proof_path,
    status
  )
  values(
    v_order_id,
    p_network,
    trim(p_sender_phone),
    trim(p_transaction_reference),
    v_deposit,
    p_amount_declared,
    nullif(trim(coalesce(p_proof_path,'')),''),
    'pending_verification'
  )
  returning id into v_payment_id;

  return jsonb_build_object(
    'orderId',v_order_id,
    'paymentId',v_payment_id,
    'orderNumber',v_order_no,
    'total',v_total,
    'depositPercent',v_deposit_percent,
    'depositAmount',v_deposit,
    'balanceAmount',v_balance,
    'status','pending_verification'
  );
end;
$$;

grant execute on function public.create_manual_mobile_order(
  jsonb,jsonb,jsonb,text,text,text,numeric,text
) to anon, authenticated;

-- ------------------------------------------------------------
-- Validation Admin de l'acompte.
-- ------------------------------------------------------------
create or replace function public.admin_verify_deposit(
  p_payment_id uuid,
  p_action text,
  p_reason text default null
)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare
  v_order_id uuid;
begin
  if not exists(
    select 1 from public.profiles p
    where p.id=auth.uid() and p.status='active'
      and p.role in ('admin','super_admin')
  ) then
    raise exception 'Accès administrateur requis';
  end if;

  select order_id into v_order_id
  from public.payment_deposits
  where id=p_payment_id;

  if v_order_id is null then
    raise exception 'Paiement introuvable';
  end if;

  if p_action='confirm' then
    update public.payment_deposits
    set status='deposit_paid',
        rejection_reason=null,
        verified_by=auth.uid(),
        verified_at=now(),
        updated_at=now()
    where id=p_payment_id;

    update public.orders
    set payment_status='deposit_paid',
        order_status='confirmed',
        balance_status='due_on_delivery',
        updated_at=now()
    where id=v_order_id;

  elsif p_action='reject' then
    update public.payment_deposits
    set status='rejected',
        rejection_reason=nullif(trim(coalesce(p_reason,'')),''),
        verified_by=auth.uid(),
        verified_at=now(),
        updated_at=now()
    where id=p_payment_id;

    update public.orders
    set payment_status='deposit_rejected',
        order_status='awaiting_deposit',
        updated_at=now()
    where id=v_order_id;

  else
    raise exception 'Action invalide';
  end if;
end;
$$;

grant execute on function public.admin_verify_deposit(uuid,text,text) to authenticated;

-- ------------------------------------------------------------
-- Solde encaissé à la livraison.
-- ------------------------------------------------------------
create or replace function public.admin_mark_balance_paid(
  p_order_id uuid
)
returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  if not exists(
    select 1 from public.profiles p
    where p.id=auth.uid() and p.status='active'
      and p.role in ('admin','super_admin')
  ) then
    raise exception 'Accès administrateur requis';
  end if;

  if not exists(
    select 1 from public.orders
    where id=p_order_id and payment_status='deposit_paid'
  ) then
    raise exception 'L''acompte doit d''abord être confirmé';
  end if;

  update public.orders
  set payment_status='paid',
      balance_status='paid',
      balance_paid_at=now(),
      order_status='delivered',
      delivery_status='delivered',
      updated_at=now()
  where id=p_order_id;
end;
$$;

grant execute on function public.admin_mark_balance_paid(uuid) to authenticated;
