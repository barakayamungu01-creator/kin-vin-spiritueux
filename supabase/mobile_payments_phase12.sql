-- KINVINS.CD — PHASE 12
create extension if not exists pgcrypto;
create table if not exists public.orders (
 id uuid primary key default gen_random_uuid(), order_number text not null unique,
 customer_name text not null, customer_phone text not null, delivery_address text not null, delivery_commune text,
 subtotal numeric(12,2) not null check(subtotal>=0), delivery_fee numeric(12,2) not null default 0 check(delivery_fee>=0),
 total numeric(12,2) not null check(total>=0), currency text not null default 'USD',
 payment_method text not null, payment_status text not null default 'pending', order_status text not null default 'awaiting_payment',
 metadata jsonb not null default '{}'::jsonb, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.order_items (
 id bigint generated by default as identity primary key, order_id uuid not null references public.orders(id) on delete cascade,
 product_id bigint references public.products(id) on delete set null, sku text, product_name text not null,
 quantity integer not null check(quantity>0), unit_price numeric(12,2) not null check(unit_price>=0),
 line_total numeric(12,2) not null check(line_total>=0), created_at timestamptz not null default now()
);
create table if not exists public.mobile_payments (
 id uuid primary key default gen_random_uuid(), order_id uuid not null references public.orders(id) on delete cascade,
 provider text not null check(provider in('mpesa','airtel_money','orange_money','cash_on_delivery')),
 customer_phone text, amount numeric(12,2) not null check(amount>=0), currency text not null default 'USD',
 status text not null default 'pending', provider_reference text, provider_transaction_id text,
 provider_response jsonb not null default '{}'::jsonb, initiated_at timestamptz not null default now(),
 completed_at timestamptz, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.mobile_payments enable row level security;
revoke all on table public.orders from anon, authenticated;
revoke all on table public.order_items from anon, authenticated;
revoke all on table public.mobile_payments from anon, authenticated;
grant select on table public.orders to authenticated;
grant select on table public.order_items to authenticated;
grant select on table public.mobile_payments to authenticated;
do $$ begin if not exists(select 1 from pg_policies where schemaname='public' and tablename='orders' and policyname='orders_admin_read') then create policy "orders_admin_read" on public.orders for select to authenticated using(exists(select 1 from public.profiles p where p.id=auth.uid() and p.status='active' and p.role in('admin','super_admin'))); end if; end $$;
do $$ begin if not exists(select 1 from pg_policies where schemaname='public' and tablename='order_items' and policyname='order_items_admin_read') then create policy "order_items_admin_read" on public.order_items for select to authenticated using(exists(select 1 from public.profiles p where p.id=auth.uid() and p.status='active' and p.role in('admin','super_admin'))); end if; end $$;
do $$ begin if not exists(select 1 from pg_policies where schemaname='public' and tablename='mobile_payments' and policyname='mobile_payments_admin_read') then create policy "mobile_payments_admin_read" on public.mobile_payments for select to authenticated using(exists(select 1 from public.profiles p where p.id=auth.uid() and p.status='active' and p.role in('admin','super_admin'))); end if; end $$;
