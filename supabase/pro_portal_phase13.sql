create or replace function public.pro_effective_discount(p_user uuid,p_product_id bigint,p_qty integer)
returns numeric language plpgsql security definer set search_path=public stable as $$
declare
  a public.pro_accounts%rowtype;
  prod public.products%rowtype;
  base_discount numeric := 0;
  rule_discount numeric := 0;
begin
  select * into a from public.pro_accounts where user_id=p_user;
  if not found or a.account_status <> 'active' then return 0; end if;
  select * into prod from public.products where id=p_product_id and active=true;
  if not found then return 0; end if;
  base_discount := case a.plan when 'essential' then 5 when 'business' then 8 when 'premium' then 12 else 0 end;
  if a.discount_override is not null then base_discount := a.discount_override; end if;
  select coalesce(max(r.discount_percent),0) into rule_discount from public.pro_price_rules r
  where r.active=true and r.plan=a.plan and r.min_qty<=greatest(p_qty,1)
    and (r.product_id is null or r.product_id=p_product_id)
    and (r.category is null or lower(r.category)=lower(prod.category));
  return least(30,greatest(base_discount,rule_discount));
end;
$$;

create or replace function public.get_pro_catalog()
returns table(id bigint,sku text,name text,category text,volume text,retail_price numeric,pro_price numeric,discount_percent numeric,stock integer,image_url text)
language sql security definer set search_path=public stable as $$
  select p.id,p.sku,p.name,p.category,p.volume,
    coalesce(nullif(p.promo_price,0),p.price)::numeric as retail_price,
    round(coalesce(nullif(p.promo_price,0),p.price)::numeric*(1-public.pro_effective_discount(auth.uid(),p.id,1)/100),2) as pro_price,
    public.pro_effective_discount(auth.uid(),p.id,1) as discount_percent,p.stock,p.image_url
  from public.products p where p.active=true order by p.category,p.name;
$$;
grant execute on function public.get_pro_catalog() to authenticated;

create or replace function public.create_pro_order(
  p_items jsonb,p_delivery_address text default null,p_delivery_commune text default null,p_delivery_date date default null
)
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  a public.pro_accounts%rowtype;
  item jsonb;
  prod public.products%rowtype;
  qty integer;
  disc numeric;
  base_price numeric;
  unit_price numeric;
  v_subtotal numeric := 0;
  v_order_id uuid;
  v_order_no text;
  v_invoice_no text;
  v_due date;
begin
  select * into a from public.pro_accounts where user_id=auth.uid();
  if not found then raise exception 'Compte KIN PRO introuvable'; end if;
  if a.account_status <> 'active' then raise exception 'Compte KIN PRO en attente de validation'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items)=0 then raise exception 'Commande vide'; end if;
  v_order_no := 'PRO-'||to_char(current_date,'YYYYMMDD')||'-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,6));
  insert into public.orders(order_number,user_id,pro_account_id,customer_name,customer_phone,delivery_address,delivery_commune,subtotal,delivery_fee,total,currency,payment_method,payment_status,order_status,delivery_date,delivery_status,metadata)
  values(v_order_no,auth.uid(),a.id,a.company,coalesce(a.phone,''),coalesce(nullif(p_delivery_address,''),a.address,''),coalesce(nullif(p_delivery_commune,''),a.commune,''),0,0,0,'USD',case when a.credit_enabled then 'pro_credit' else 'pro_invoice' end,'invoice_due','confirmed',p_delivery_date,case when p_delivery_date is null then 'not_scheduled' else 'scheduled' end,jsonb_build_object('source','kin_pro_portal','plan',a.plan))
  returning id into v_order_id;
  for item in select * from jsonb_array_elements(p_items) loop
    qty := greatest(1,coalesce((item->>'quantity')::integer,1));
    select * into prod from public.products where id=(item->>'productId')::bigint and active=true;
    if not found then raise exception 'Produit introuvable'; end if;
    base_price := coalesce(nullif(prod.promo_price,0),prod.price);
    disc := public.pro_effective_discount(auth.uid(),prod.id,qty);
    unit_price := round(base_price*(1-disc/100),2);
    v_subtotal := v_subtotal + unit_price*qty;
    insert into public.order_items(order_id,product_id,sku,product_name,quantity,unit_price,line_total)
    values(v_order_id,prod.id,prod.sku,prod.name,qty,unit_price,round(unit_price*qty,2));
  end loop;
  update public.orders set subtotal=v_subtotal,total=v_subtotal,updated_at=now() where id=v_order_id;
  v_invoice_no := 'INV-'||to_char(current_date,'YYYYMMDD')||'-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,6));
  v_due := current_date + greatest(a.payment_terms_days,0);
  insert into public.pro_invoices(user_id,pro_account_id,order_id,invoice_number,amount,currency,due_date,status)
  values(auth.uid(),a.id,v_order_id,v_invoice_no,v_subtotal,'USD',v_due,'unpaid');
  return jsonb_build_object('orderId',v_order_id,'orderNumber',v_order_no,'invoiceNumber',v_invoice_no,'total',v_subtotal,'dueDate',v_due);
end;
$$;
grant execute on function public.create_pro_order(jsonb,text,text,date) to authenticated;
